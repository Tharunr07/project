/** Bill arithmetic — kept here so the preview and the list always agree. */
export function deriveBillTotals(bill) {
  const subtotal = (Number(bill.travellers) || 0) * (Number(bill.pricePerPerson) || 0)
  const extras = (bill.extraCharges || []).reduce((sum, c) => sum + (Number(c.amount) || 0), 0)
  const discount = Number(bill.discount) || 0
  const grandTotal = subtotal + extras - discount
  const advancePaid = Number(bill.advancePaid) || 0
  const balanceDue = grandTotal - advancePaid
  return { subtotal, extras, discount, grandTotal, advancePaid, balanceDue }
}

